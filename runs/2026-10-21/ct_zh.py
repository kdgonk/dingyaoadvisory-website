import re, pathlib

def add(path, pairs):
    p = pathlib.Path(path); s = p.read_text(encoding="utf-8"); n = 0
    for key, suffix in pairs:
        i = s.find(key)
        assert i >= 0, f"{path}: key not found -> {key[:40]}"
        li_at = s.rfind("<li", 0, i); p_at = s.rfind("<p", 0, i)
        if li_at > p_at:
            en = s.find("</li>", i)
        else:
            en = s.find("</p>", i)
        assert en > 0
        s = s[:en] + suffix + s[en:]
        n += 1
    p.write_text(s, encoding="utf-8"); return n

